import assert from 'node:assert/strict'
import {createHmac} from 'node:crypto'
import {createRequire} from 'node:module'
import {createConnection} from 'mysql2/promise'
import {mkdirSync} from 'node:fs'
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
const base=process.env.TEST_BASE_URL||'http://localhost:3002'
assert.ok(['localhost','127.0.0.1'].includes(new URL(base).hostname))
assert.equal(new URL(process.env.DATABASE_URL).hostname,'127.0.0.1')
const db=await createConnection(process.env.DATABASE_URL)
const [[original]]=await db.query('SELECT * FROM plot_map_state WHERE id=1')
const revisions=[]
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE})
const publicMap=async()=>{const r=await fetch(base+'/api/camp');assert.equal(r.status,200);const data=await r.json();return data}
try {
  const before=await publicMap()
  const ctx=await browser.newContext({viewport:{width:1440,height:1000}})
  const expiry=String(Date.now()+600000)
  await ctx.addCookies([{name:'trunkhill_admin',value:expiry+'.'+createHmac('sha256',process.env.ADMIN_SESSION_SECRET).update(expiry).digest('hex'),url:base}])
  const page=await ctx.newPage(),errors=[];page.setDefaultTimeout(20000);page.on('pageerror',e=>errors.push(e.message))
  await page.goto(base+'/admin?section=plotMap',{waitUntil:'networkidle'})
  await page.getByRole('heading',{name:'จัดการผังลาน',exact:true,level:2}).waitFor()
  assert.equal(await page.getByRole('button',{name:'จุดตำแหน่ง',exact:true}).count(),0)
  const polygon=page.locator('polygon[aria-label="พื้นที่ A01"]')
  const originalPoints=await polygon.getAttribute('points')
  const handle=page.getByRole('button',{name:'จุดที่ 1 ของ A01',exact:true})
  await handle.scrollIntoViewIfNeeded();const box=await handle.boundingBox()
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();await page.mouse.move(box.x+box.width/2+18,box.y+box.height/2+8,{steps:5});await page.mouse.up()
  assert.notEqual(await polygon.getAttribute('points'),originalPoints,'vertex dragged directly')
  await page.getByRole('button',{name:'ขยายผัง',exact:true}).click();assert.equal(await page.locator('.map-zoom-controls output').innerText(),'125%')
  await page.getByRole('button',{name:'พอดีจอ',exact:true}).click()
  await page.locator('.map-element-list button').filter({hasText:'A02'}).click()
  await page.getByRole('button',{name:'ลบพื้นที่',exact:true}).click()
  assert.equal(await page.locator('polygon[aria-label="พื้นที่ A02"]').count(),0)
  await page.getByRole('button',{name:'↶ ย้อนกลับ',exact:true}).click()
  assert.equal(await page.locator('polygon[aria-label="พื้นที่ A02"]').count(),1)
  await page.getByRole('button',{name:'ลบพื้นที่',exact:true}).click()
  await page.getByRole('button',{name:'วาดรูปหลายเหลี่ยม',exact:true}).click()
  await page.locator('.map-studio-viewport').scrollIntoViewIfNeeded()
  const area=await page.locator('.map-studio-viewport').boundingBox()
  for(const [x,y] of [[80,40],[180,40],[180,130],[80,130]])await page.mouse.click(area.x+x,area.y+y)
  await page.getByRole('button',{name:'จบการวาด',exact:true}).click()
  const drawn=page.locator('polygon[aria-label="พื้นที่ A02"]')
  assert.equal((await drawn.getAttribute('points')).split(' ').length,4,'polygon drawing')
  const drawnPoints=await drawn.getAttribute('points')
  await page.mouse.move(area.x+130,area.y+85);await page.mouse.down();await page.mouse.move(area.x+145,area.y+95,{steps:5});await page.mouse.up()
  assert.notEqual(await drawn.getAttribute('points'),drawnPoints,'move whole element')
  await page.getByRole('button',{name:'ลบพื้นที่',exact:true}).click()
  await page.getByLabel('รูปผังลาน',{exact:true}).setInputFiles('public/camp-map.webp')
  await page.getByRole('button',{name:'บันทึก Draft',exact:true}).click()
  await page.getByRole('status').filter({hasText:'บันทึก Draft แล้ว'}).waitFor()
  const [[draft]]=await db.query('SELECT * FROM plot_map_state WHERE id=1');revisions.push(draft.draft_revision)
  assert.equal(draft.published_revision,original.published_revision)
  const afterDraft=await publicMap()
  assert.deepEqual(afterDraft.inventory,before.inventory,'Draft does not alter customer inventory/map')
  assert.equal(afterDraft.settings.map_version,before.settings.map_version)
  assert.equal((await fetch(base+'/api/plot-map-image?v='+draft.draft_revision)).status,404,'draft image not public')
  assert.equal((await fetch(base+'/admin/plot-map-preview?v='+draft.draft_revision)).status,403,'preview protected')
  await page.reload({waitUntil:'networkidle'})
  assert.equal(await page.locator('polygon[aria-label="พื้นที่ A02"]').count(),0,'deleted element persists in draft')
  await page.getByRole('button',{name:'พรีวิว',exact:true}).click()
  await page.getByRole('dialog',{name:'พรีวิวหน้าผู้จอง'}).waitFor()
  const frame=page.frameLocator('iframe')
  await frame.locator('.map-customer-view').waitFor()
  assert.equal(await frame.locator('[aria-label^="A02 ·"]').count(),0)
  await page.getByRole('button',{name:'คอมพิวเตอร์ · 1100px'}).click()
  assert.ok(await page.locator('iframe').evaluate(el=>el.contentWindow.innerWidth>=1098&&el.contentWindow.innerWidth<=1100))
  await page.getByRole('button',{name:'มือถือ · 390px'}).click()
  assert.ok(await page.locator('iframe').evaluate(el=>el.contentWindow.innerWidth>=388&&el.contentWindow.innerWidth<=390))
  assert.ok(await page.locator('iframe').evaluate(el=>el.contentDocument.documentElement.scrollWidth<=390))
  await page.getByRole('button',{name:'ปิดพรีวิว'}).click()
  await page.getByRole('button',{name:'Publish',exact:true}).click()
  await page.getByRole('button',{name:'ยืนยัน Publish',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Publish แล้ว'}).waitFor()
  const [[published]]=await db.query('SELECT * FROM plot_map_state WHERE id=1');revisions.push(published.draft_revision)
  const customer=await publicMap()
  assert.equal(customer.settings.map_version,published.published_revision)
  assert.equal(customer.inventory.find(i=>i.code==='A02').map_hidden,true)
  assert.notEqual(customer.inventory.find(i=>i.code==='A01').map_shape,before.inventory.find(i=>i.code==='A01').map_shape)
  assert.equal((await fetch(base+'/api/plot-map-image?v='+published.published_revision)).status,200)
  mkdirSync('tmp/map-studio',{recursive:true});await page.screenshot({path:'tmp/map-studio/desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:'tmp/map-studio/mobile.png',fullPage:true})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'admin mobile no page overflow')
  const anonymous=await browser.newPage({viewport:{width:390,height:844}})
  await anonymous.goto(base+'/',{waitUntil:'networkidle'})
  await anonymous.locator('.map-customer-view').first().waitFor()
  const customerPolygon=anonymous.locator('.map-customer-view polygon[aria-label^="A01 ·"]').first()
  await customerPolygon.waitFor()
  assert.equal(await customerPolygon.getAttribute('points'),customer.inventory.find(i=>i.code==='A01').map_shape?JSON.parse(customer.inventory.find(i=>i.code==='A01').map_shape).points.map(p=>p.join(',')).join(' '):'')
  await customerPolygon.click({force:true})
  assert.equal(await customerPolygon.getAttribute('aria-pressed'),'true','customer can select published element')
  assert.equal(await anonymous.locator('.map-customer-view [aria-label^="A02 ·"]').count(),0)
  assert.ok(await anonymous.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'customer mobile no page overflow')
  await anonymous.screenshot({path:'tmp/map-studio/customer-mobile.png',fullPage:true})
  await anonymous.setViewportSize({width:1440,height:1000});await anonymous.screenshot({path:'tmp/map-studio/customer-desktop.png',fullPage:true})
  assert.equal(errors.length,0,errors.join('\n'))
  console.log('PASS: direct vertex drag, zoom, delete/undo, batch draft persistence, private preview, mobile/desktop preview, atomic publish, public map/image alignment, and customer responsive layout.')
} finally {
  await browser.close()
  const [[current]]=await db.query('SELECT * FROM plot_map_state WHERE id=1')
  if(revisions.includes(current.draft_revision)) {
    await db.execute('UPDATE plot_map_state SET draft_revision=?,published_revision=? WHERE id=1',[original.draft_revision,original.published_revision])
    for(const revision of revisions)await db.execute('DELETE FROM plot_map_versions WHERE revision=?',[revision])
  }
  await db.end()
}
