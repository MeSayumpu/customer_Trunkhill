CREATE TABLE IF NOT EXISTS storage_quota (
 id INT PRIMARY KEY, limit_bytes BIGINT UNSIGNED NOT NULL DEFAULT 10000000000,
 system_bytes BIGINT UNSIGNED NOT NULL DEFAULT 0, measured_at DATETIME NULL
) ENGINE=InnoDB;
INSERT IGNORE INTO storage_quota(id) VALUES (1);
CREATE TABLE IF NOT EXISTS storage_assets (
 id CHAR(36) PRIMARY KEY, owner VARCHAR(100) NOT NULL, bytes BIGINT UNSIGNED NOT NULL,
 received BIGINT UNSIGNED NOT NULL DEFAULT 0, mime VARCHAR(40) NULL, file_hash CHAR(64) NULL,
 claimed BOOLEAN NOT NULL DEFAULT FALSE, expires_at DATETIME NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS storage_chunks (
 asset CHAR(36) NOT NULL, part INT UNSIGNED NOT NULL, content MEDIUMBLOB NOT NULL,
 PRIMARY KEY(asset,part), FOREIGN KEY(asset) REFERENCES storage_assets(id) ON DELETE CASCADE
) ENGINE=InnoDB;
